export function montarTermoResolvido(
  dados: {
    nomeCompleto?: string;
    rg?: string;
    cpf?: string;
    dataNascimento?: string;
    estadoCivil?: string;
    endereco?: string;
    nomeMae?: string;
    nomePai?: string;
    pis?: string;
    email?: string;
    whatsapp?: string;
    telefone?: string;
    matricula?: string;
    profissoes?: string[];
  },
  allTerms: Termo[]
): { title: string; text: string } {
  const profissoesList = (dados.profissoes || []).map(p => (p || '').trim()).filter(Boolean);
  const professionsText = profissoesList.join(', ') || 'Cooperado';
  const nomeCompleto = (dados.nomeCompleto || '').trim();
  const rg = (dados.rg || '').trim();
  const cpf = (dados.cpf || '').trim();
  const dataNascimento = dados.dataNascimento;
  const estadoCivil = (dados.estadoCivil || '').trim();
  const endereco = (dados.endereco || '').trim();
  const nomeMae = (dados.nomeMae || '').trim();
  const nomePai = (dados.nomePai || '').trim();
  const pis = (dados.pis || '').trim();
  const email = (dados.email || '').trim();
  const telefone = (dados.whatsapp || dados.telefone || '').trim();
  const matricula = (dados.matricula || '').trim();
  const currentDate = new Date().toLocaleDateString('pt-BR');

  // 1. Busca termo ativo para uma das profissões
  let activeTerm = (allTerms || []).find(
    (t) => t?.bool_ativo && profissoesList.some((p) => p.toLowerCase() === (t?.txt_profissao || '').toLowerCase().trim())
  );

  // 2. Busca termo ativo 'Geral' ou 'Todos'
  if (!activeTerm) {
    activeTerm = (allTerms || []).find(
      (t) => t?.bool_ativo && ['geral', 'todos'].includes((t?.txt_profissao || '').toLowerCase().trim())
    );
  }

  // 3. Fallback para qualquer termo ativo
  if (!activeTerm) {
    activeTerm = (allTerms || []).find((t) => t?.bool_ativo);
  }

  let templateText = activeTerm?.txt_conteudo;
  const title = activeTerm?.txt_titulo || 'TERMO DE ADESÃO MULTCARE - GERAL';

  // Fallback padrão se não houver no banco ou estiver vazio
  if (!templateText || typeof templateText !== 'string' || !templateText.trim()) {
    templateText = DEFAULT_TERMO_MULTCARE;
  }

  // Substituição de marcadores
  const resolvedText = templateText
    .replace(/{nome}/gi, nomeCompleto.toUpperCase())
    .replace(/{nomeCompleto}/gi, nomeCompleto.toUpperCase())
    .replace(/{rg}/gi, rg)
    .replace(/{cpf}/gi, cpf)
    .replace(/{dataNascimento}/gi, dataNascimento ? new Date(dataNascimento).toLocaleDateString('pt-BR') : '')
    .replace(/{estadoCivil}/gi, estadoCivil)
    .replace(/{endereco}/gi, endereco)
    .replace(/{profissoes}/gi, professionsText)
    .replace(/{nomeMae}/gi, nomeMae.toUpperCase())
    .replace(/{nomePai}/gi, nomePai.toUpperCase())
    .replace(/{pis}/gi, pis)
    .replace(/{email}/gi, email)
    .replace(/{telefone}/gi, telefone)
    .replace(/{matricula}/gi, matricula)
    .replace(/{dataAtual}/gi, currentDate);

  return { title, text: resolvedText || '' };
}
